export const getCategoryForItem = (item) => {
  if (!item) return "aluminum_profile";
  
  if (item.category && [
    "aluminum_profile",
    "customized_workstation",
    "pipe_joints",
    "fifo_rack",
    "machine_guarding",
    "ms_fabrication"
  ].includes(item.category)) {
    return item.category;
  }

  const src = item.src || "";
  const title = (item.title || "").toLowerCase();
  const desc = (item.desc || "").toLowerCase();

  if (src.includes("/workstations/") || (title.includes("workstation") && !title.includes("pipe")) || title.includes("workbench")) {
    return "customized_workstation";
  }

  if (src.includes("/pipe_joint/") || title.includes("pipe") || title.includes("joint")) {
    return "pipe_joints";
  }

  if (
    src.includes("/protection-systems/") ||
    src.includes("/Protection System/") ||
    title.includes("guard") ||
    title.includes("shield") ||
    title.includes("enclosure") ||
    title.includes("fence") ||
    title.includes("barrier") ||
    title.includes("partition")
  ) {
    return "machine_guarding";
  }

  if (
    src.includes("/conveyor/") ||
    title.includes("flow rack") ||
    title.includes("fifo") ||
    title.includes("conveyor") ||
    title.includes("roller") ||
    desc.includes("flow rack") ||
    desc.includes("fifo")
  ) {
    return "fifo_rack";
  }

  if (
    src.includes("/Have duty app/") ||
    src.includes("/Profile Assembly System/") ||
    title.includes("gantry") ||
    title.includes("fabrication") ||
    title.includes("heavy") ||
    title.includes("structure") ||
    title.includes("welding")
  ) {
    return "ms_fabrication";
  }

  return "aluminum_profile";
};
